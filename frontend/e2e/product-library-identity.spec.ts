import { expect, test } from "@playwright/test";
import { spawn, execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import path from "node:path";
import { installApiMock } from "./support/api-mock";

const api = "http://127.0.0.1:8218/api/product-library";

test("migrated SQLite + real Excel: exact duplicate update, partial identity inserts and cross-page receipt", async ({ page, request }) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width: 1440, height: 1200 });
  let releaseConfirm!: () => void;
  const confirmGate = new Promise<void>(resolve => { releaseConfirm = resolve; });
  const repo = path.resolve("..");
  const venvPython = path.join(repo, ".venv/Scripts/python.exe");
  const python = existsSync(venvPython) ? venvPython : "python";
  const server = spawn(python, ["-m", "tests.library_browser_server", "--port", "8218"], { cwd: path.join(repo, "backend"), windowsHide: true, stdio: "pipe" });
  let errors = ""; server.stderr.on("data", value => { errors += value.toString(); });
  try {
    await expect.poll(async () => { try { return (await request.get(api + "/manufacturers")).status(); } catch { if (server.exitCode !== null) throw new Error(errors); return 0; } }, { timeout: 30000 }).toBe(200);
    async function create(model: string, name: string, extra = {}) {
      const response = await request.post(api + "/products", { data: { manufacturer_name: "身份验收", model, name, allow_suspected_duplicate: true, ...extra } });
      expect(response.status()).toBe(201); return response.json();
    }
    const a = await create("M", "原产品 A", { parameters: "原参数 A", wholesale_price: "10.00" });
    const b = await create("M", "原产品 B", { parameters: "原参数 B", wholesale_price: "20.00" });
    await create("Q", "同名候选", { parameters: "候选完整参数", selling_points: "候选完整卖点", wholesale_price: "30.00", price_note: "仅内部核对备注" });
    await installApiMock(page, { competitors: [] });
    const confirms: any[] = [];
    await page.route("**/api/product-library/**", async route => {
      const url = new URL(route.request().url());
      if (url.pathname.endsWith("/confirm")) confirms.push(route.request().postDataJSON());
      const response = await route.fetch({ url: `http://127.0.0.1:8218${url.pathname}${url.search}`, postData: route.request().postDataBuffer() ?? undefined });
      if (url.pathname.endsWith("/confirm")) await confirmGate;
      await route.fulfill({ response });
    });
    await page.goto("/");
    await page.getByRole("button", { name: "产品库", exact: true }).click();
    await expect(page.getByLabel("厂家筛选")).toContainText("身份验收");
    // A same-model, different-name product is a normal insert.
    await page.getByRole("button", { name: "手动新增", exact: true }).click();
    let dialog = page.getByRole("dialog");
    await dialog.getByLabel("厂家名称").fill("身份验收");
    await dialog.getByLabel("产品型号", { exact: true }).fill("M");
    await dialog.getByLabel("产品名称", { exact: false }).fill("手动独立产品");
    await dialog.getByRole("button", { name: "保存", exact: true }).click();
    await expect(dialog).toHaveCount(0);
    const manual = (await (await request.get(api + "/products", { params: { manufacturer: "身份验收", q: "手动独立产品" } })).json()).items[0];
    await page.getByLabel("厂家筛选").selectOption("身份验收");
    const manualRow = page.getByRole("row").filter({ has: page.getByRole("cell", { name: "手动独立产品", exact: true }) });
    await manualRow.getByRole("button", { name: "编辑", exact: true }).click();
    dialog = page.getByRole("dialog");
    await dialog.getByLabel("产品名称", { exact: false }).fill("手动改名后");
    await dialog.getByRole("button", { name: "保存", exact: true }).click();
    await expect(dialog).toHaveCount(0);
    const changed = await (await request.get(api + `/products/${manual.id}`)).json();
    expect(changed.id).toBe(manual.id); expect(changed.version).toBe(manual.version + 1);
    const rows = [["M", "原产品 B", "更新参数 B"], ["M", "导入独立 D"], ["N", "同名候选"], [null, "无型号名称", "规格1"], [null, "无型号名称", "规格2"], ["M", "原产品 A"], ["BAD", null], ["DUP", "精确重复"], ["DUP", "精确重复"], ...Array.from({ length: 25 }, (_, i) => [`NEW-${i}`, `普通新品 ${i}`])];
    const workbook = Buffer.from(execFileSync(python, ["-c", "import sys,json,io,base64; from openpyxl import Workbook; w=Workbook(); s=w.active; s.title='产品数据'; s.append(['产品型号','产品名称','产品参数','产品卖点','批发价','价格备注']); [s.append(r) for r in json.loads(sys.stdin.buffer.read().decode('utf-8'))]; b=io.BytesIO(); w.save(b); print(base64.b64encode(b.getvalue()).decode())"], { input: JSON.stringify(rows), encoding: "utf8", windowsHide: true }).trim(), "base64");
    await page.getByRole("button", { name: "批量导入", exact: true }).click();
    dialog = page.getByRole("dialog");
    await dialog.getByLabel("厂家名称").fill("身份验收");
    await dialog.getByLabel("Excel 文件").setInputFiles({ name: "真实身份验收.xlsx", mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", buffer: workbook });
    const previewEvent = page.waitForResponse(response => response.url().includes("/imports/preview?"));
    await dialog.getByRole("button", { name: "上传并预览" }).click();
    const preview = await (await previewEvent).json();
    expect(preview, JSON.stringify(preview)).toHaveProperty("identity_rule_version", 3);
    await dialog.getByLabel("第 2 行操作", { exact: true }).selectOption("update");
    await expect(dialog.getByRole("alert")).toContainText("请核对第 2 行目标");
    await expect(dialog.getByText("原参数 B", { exact: true })).toBeVisible();
    page.once("dialog", event => event.accept());
    await dialog.getByLabel("第 2 行操作", { exact: true }).selectOption("update");
    await expect(dialog.getByText("更新参数 B", { exact: true })).toBeVisible();
    const parameterRow = dialog.locator(".library-diff tr").filter({ has: page.getByRole("rowheader", { name: "产品参数", exact: true }) });
    await expect(parameterRow.locator("td").last()).toHaveText("更新参数 B（变更）");
    await expect(dialog.locator(".library-preview-row").filter({ hasText: "第 2 行" }).locator("small.library-match").first()).toHaveText("同厂家、同型号、同名称已存在");
    await page.screenshot({ path: "../docs/qa/product-library-identity-v2/01-exact-duplicate-review.png" });
    await dialog.getByRole("button", { name: "下一页", exact: true }).click();
    await dialog.getByLabel("第 31 行操作", { exact: true }).selectOption("skip");
    await dialog.getByLabel("审核状态", { exact: true }).selectOption("duplicate");
    await expect(dialog.getByLabel("第 2 行操作", { exact: true })).toHaveValue("update");
    await page.screenshot({ path: "../docs/qa/product-library-identity-v2/02-duplicate-filter.png" });
    const receiptEvent = page.waitForResponse(response => response.url().endsWith("/confirm"));
    await dialog.getByRole("button", { name: "确认导入", exact: true }).click();
    await expect(dialog.getByLabel("第 2 行对比候选", { exact: true })).toBeDisabled();
    await expect(dialog.getByLabel("第 2 行更新目标", { exact: true })).toBeDisabled();
    releaseConfirm();
    const receipt = await (await receiptEvent).json();
    expect(receipt).toMatchObject({ status: "committed", inserted: 28, updated: 1, skipped: 4, invalid: 1 });
    expect(confirms).toHaveLength(1);
    expect(confirms[0].decisions.find((row: any) => row.row_number === 2)).toMatchObject({ action: "update", target_id: b.id, target_version: b.version });
    const savedB = await (await request.get(api + `/products/${b.id}`)).json();
    expect(savedB).toMatchObject({ id: b.id, name: "原产品 B", parameters: "更新参数 B", version: b.version + 1 });
    expect(await (await request.get(api + `/products/${a.id}`)).json()).toEqual(a);
    const d = (await (await request.get(api + "/products", { params: { manufacturer: "身份验收", q: "导入独立 D" } })).json()).items[0];
    expect(d.parameters).toBeNull(); expect(d.model).toBe("M");
    await dialog.getByLabel("执行结果", { exact: true }).selectOption("inserted");
    await page.screenshot({ path: "../docs/qa/product-library-identity-v2/03-results.png" });
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);
    await page.screenshot({ path: "../docs/qa/product-library-identity-v2/04-narrow-results.png" });
    await dialog.getByRole("button", { name: "返回列表", exact: true }).click();
  } finally { releaseConfirm(); server.kill(); }
});
