test("clear combined filters clears selection and ignores delayed old queries", async ({ page }) => {
  await emptySetup(page);
  const product = { id: 1, version: 1, manufacturer_name: "厂家", model: "QA", name: "组合筛选产品", wholesale_price: "10.00", updated_at: "2026-10-20T00:00:00Z" };
  let release!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  const queries: URLSearchParams[] = [];
  await page.route("**/api/product-library/products?*", async route => {
    const params = new URL(route.request().url()).searchParams; queries.push(params);
    if (params.get("q") === "迟到") { await gate; await route.fulfill({ json: { items: [{ ...product, name: "迟到旧结果" }], total: 999 } }); }
    else await route.fulfill({ json: { items: [product], total: 1 } });
  });
  await page.getByRole("button", { name: "刷新", exact: true }).click();
  await page.getByLabel("选择产品 1", { exact: true }).check();
  await page.getByLabel("厂家筛选").selectOption("厂家");
  await page.getByLabel("报价状态", { exact: true }).selectOption("quoted");
  await page.getByLabel("排序", { exact: true }).selectOption("price_desc");
  await page.getByLabel("价格条件", { exact: true }).selectOption("between");
  await page.getByLabel("最低价", { exact: true }).fill("0");
  await page.getByLabel("最高价", { exact: true }).fill("20");
  await page.getByLabel("产品库关键词").fill("迟到");
  await expect.poll(() => queries.some(params => params.get("q") === "迟到")).toBe(true);
  await page.getByRole("button", { name: "清空筛选", exact: true }).click();
  await expect(page.getByRole("cell", { name: product.name, exact: true })).toBeVisible();
  release();
  await expect(page.getByText("跨页已选 0 款", { exact: true })).toBeVisible();
  await expect(page.getByLabel("价格条件", { exact: true })).toHaveValue("");
  await expect(page.getByLabel("产品库关键词")).toHaveValue("");
  const params = queries.at(-1)!;
  expect(Object.fromEntries(params)).toEqual({ q: "", sort: "updated_desc", price_status: "all", page: "1", page_size: "20" });
  await expect(page.getByText("迟到旧结果", { exact: true })).toHaveCount(0);
  await page.screenshot({ path: "../docs/qa/product-library-vnext/01-clear-filters.png", fullPage: true });
});

