import { test, expect } from "@playwright/test";
import { spawn, execFileSync } from "node:child_process";
import path from "node:path";
import { installApiMock } from "./support/api-mock";

const directory = "../docs/qa/customer-quotation-upgrade";

test("customer quotation: MOQ, multiline note, integer manual price, safety, stale recovery and real Excel", async ({ page, request }) => {
  test.setTimeout(90000);
  const repo = path.resolve("..");
  const python = path.join(repo, ".venv/Scripts/python.exe");
  const server = spawn(python, ["-m", "tests.library_browser_server", "--port", "8219"], { cwd: path.join(repo, "backend"), windowsHide: true, stdio: "pipe" });
  let stderr = ""; server.stderr.on("data", data => { stderr += data; });
  const api = "http://127.0.0.1:8219/api/product-library";
  try {
    await expect.poll(async () => { try { return (await request.get(api + "/manufacturers")).status(); } catch { if (server.exitCode !== null) throw Error(stderr); return 0; } }, { timeout: 30000 }).toBe(200);
    const original = await (await request.get(api + "/products/45")).json();
    await installApiMock(page, { competitors: [] });
    await page.route("**/api/product-library/**", async route => {
      const url = new URL(route.request().url());
      await route.fulfill({ response: await route.fetch({ url: `http://127.0.0.1:8219${url.pathname}${url.search}` }) });
    });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto("/");
    await page.getByRole("button", { name: "产品库", exact: true }).click();
    await page.getByLabel("选择产品 45", { exact: true }).check();
    await page.getByRole("button", { name: "客户报价 Excel", exact: true }).click();
    const dialog = page.getByRole("dialog");
    const moq = dialog.getByLabel("统一 MOQ（起订量）");
    await moq.fill("0");
    await dialog.getByRole("button", { name: "生成报价预览", exact: true }).click();
    await expect(dialog.getByRole("alert")).toContainText("MOQ 必须");
    await moq.fill("120");
    await dialog.getByLabel("最终取整").selectOption("integer");
    const note = "=客户说明\n以上报价含税，运费另计\n内部价需客户文本核查";
    await dialog.getByLabel("报价说明", { exact: true }).fill(note);
    await page.screenshot({ path: `${directory}/01-config.png` });
    await dialog.getByRole("button", { name: "生成报价预览", exact: true }).click();
    await expect(dialog.getByLabel("最终报价 45", { exact: true })).toHaveValue("11.00");
    await expect(dialog.getByRole("columnheader")).toHaveText(["型号 / 名称", "原始报价仅内部，不导出", "最终报价元 / 件，可直接修改"]);
    await expect(dialog.getByRole("cell", { name: "10.46", exact: true })).toBeVisible();
    await dialog.getByLabel("最终报价 45", { exact: true }).fill("9.21");
    await expect(dialog.getByRole("button", { name: "下载客户 Excel" })).toBeDisabled();
    await dialog.getByRole("button", { name: "重新核算报价" }).click();
    await expect(dialog.getByLabel("最终报价 45", { exact: true })).toHaveValue("10.00");
    await expect(dialog.getByText("低于采购成本", { exact: true })).toBeVisible();
    await dialog.getByRole("button", { name: "查看客户可见参数和卖点" }).click();
    await expect(dialog.getByText("3.7V，客户参数", { exact: true })).toBeVisible();
    await expect(dialog.getByLabel("客户报价说明预览").locator("p.library-text")).toHaveText(note);
    await dialog.getByLabel("已核对全部客户可见产品文本与报价说明").check();
    await expect(dialog.getByRole("button", { name: "下载客户 Excel" })).toBeDisabled();
    await dialog.getByLabel("已核查报价说明中的敏感文本").check();
    await expect(dialog.getByRole("button", { name: "下载客户 Excel" })).toBeEnabled();
    await page.screenshot({ path: `${directory}/02-review-desktop.png` });
    // Any changed condition invalidates all previous confirmations.
    await dialog.locator("summary").click();
    await moq.fill("121");
    await expect(dialog.getByLabel("已核查报价说明中的敏感文本")).not.toBeChecked();
    await expect(dialog.getByLabel("已核对全部客户可见产品文本与报价说明")).not.toBeChecked();
    await dialog.getByRole("button", { name: "重新核算报价" }).click();
    await dialog.getByLabel("已核查报价说明中的敏感文本").check();
    await dialog.getByLabel("已核对全部客户可见产品文本与报价说明").check();
    const downloadEvent = page.waitForEvent("download");
    await dialog.getByRole("button", { name: "下载客户 Excel" }).click();
    const download = await downloadEvent;
    const file = `${directory}/customer-quotation.xlsx`;
    await download.saveAs(file);
    const values = JSON.parse(execFileSync(python, ["-c", "import sys,json,zipfile; from openpyxl import load_workbook; w=load_workbook(sys.argv[1]); s=w.active; assert s.max_column==7; assert len(w.worksheets)==1 and s.sheet_state=='visible'; assert not any(c.data_type=='f' or c.comment for r in s for c in r); assert not any(d.hidden for d in s.column_dimensions.values()); assert s['G2'].data_type=='s'; z=zipfile.ZipFile(sys.argv[1]); raw=b''.join(z.read(n) for n in z.namelist()); assert b'PRIVATE_INTERNAL_NOTE' not in raw and b'10.46' not in raw; print(json.dumps(list(s.values),ensure_ascii=True))", file], { encoding: "utf8", windowsHide: true }));
    expect(values[0]).toEqual(["产品型号", "产品名称", "完整参数", "卖点", "最终报价", "MOQ", "报价说明"]);
    expect(values[1]).toEqual([original.model, original.name, original.parameters, original.selling_points, 10, 121, note]);
    expect(await (await request.get(api + "/products/45")).json()).toEqual(original);
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
    await dialog.getByRole("button", { name: "下载客户 Excel" }).scrollIntoViewIfNeeded();
    await expect(dialog.getByRole("button", { name: "下载客户 Excel" })).toBeInViewport();
    await page.screenshot({ path: `${directory}/03-review-narrow.png` });
    await dialog.locator("summary").click();
    await moq.scrollIntoViewIfNeeded();
    await page.screenshot({ path: `${directory}/04-config-narrow.png` });
    await dialog.getByLabel("报价说明", { exact: true }).fill("更新后的客户说明\n运费另计");
    await expect(dialog.getByRole("button", { name: "下载客户 Excel" })).toBeDisabled();
    await dialog.getByRole("button", { name: "重新核算报价" }).click();
    await dialog.getByLabel("已核对全部客户可见产品文本与报价说明").check();
    // Actual API stale-version rejection and refresh preserve this quote's conditions.
    const { id, version, created_at, updated_at, ...fields } = original;
    expect((await request.put(api + "/products/45", { data: { ...fields, version, name: "验收灯 45 更新" } })).status()).toBe(200);
    await dialog.getByRole("button", { name: "下载客户 Excel" }).click();
    await expect(dialog.getByRole("alert").filter({ hasText: "需刷新并复核" })).toBeVisible();
    await dialog.getByRole("button", { name: "重新核算报价" }).click();
    await expect(dialog.getByText("验收灯 45 更新", { exact: true }).first()).toBeVisible();
    await expect(dialog.getByLabel("最终报价 45", { exact: true })).toHaveValue("10.00");
    await expect(dialog.getByLabel("客户报价说明预览").locator("p.library-text")).toHaveText("更新后的客户说明\n运费另计");
  } finally { server.kill(); }
});
